import { fireEvent, screen, waitFor, within } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { toast } from 'sonner'
import { FacturacionPage } from '@/features/facturacion/facturacion-page'
import { json, renderWithSession as render } from '../../support/session'
import { factura, failure, invoiceResult, mockBilling, orden, posts } from './fixtures'

afterEach(() => { vi.unstubAllGlobals(); vi.restoreAllMocks() })
async function newInvoice() {
  fireEvent.click(screen.getByRole('button', { name: 'Nueva factura' }))
  await waitFor(() => expect(screen.getByLabelText('Orden *')).toBeEnabled())
  fireEvent.click(await screen.findByRole('option', { name: 'OS-2' }))
  await waitFor(() => expect(screen.getByRole('button', { name: 'Revisar y generar' })).toBeEnabled())
}
async function reviewInvoice() {
  await newInvoice()
  fireEvent.change(screen.getByLabelText('Nombre de facturación'), { target: { value: '  Ana Fiscal  ' } })
  fireEvent.click(screen.getByRole('button', { name: 'Revisar y generar' }))
  return screen.findByRole('dialog', { name: 'Confirmar generación de factura' })
}
async function reviewCancellation() {
  fireEvent.click(await screen.findByRole('button', { name: 'Ver factura F-1' }))
  const button = await screen.findByRole('button', { name: /Anular pago #1/ })
  await waitFor(() => expect(button).toBeEnabled())
  fireEvent.click(button)
  fireEvent.change(screen.getByLabelText('Motivo de anulación *'), { target: { value: '  Referencia equivocada  ' } })
  fireEvent.click(screen.getByRole('button', { name: 'Revisar anulación' }))
  return screen.findByRole('dialog', { name: 'Confirmar anulación de pago' })
}

describe('emisión desde orden con resumen oficial', () => {
  it('no selecciona primera orden, permite búsqueda/página remotas y conserva selección entre páginas', async () => {
    const fetchMock = mockBilling(url => {
      if (url.pathname !== '/api/v1/ordenes') return undefined
      const current = Number(url.searchParams.get('page'))
      const size = Number(url.searchParams.get('pageSize'))
      return json({ data: size > 10 ? [{ ...orden, idOrden: 20, numeroOrden: 'OS-20' }, orden] : [{ ...orden, idOrden: 20, numeroOrden: 'OS-20' }], meta: { page: current, pageSize: size, total: 25, totalPages: 3 } })
    })
    render(<FacturacionPage />)
    fireEvent.click(screen.getByRole('button', { name: 'Nueva factura' }))
    await waitFor(() => expect(screen.getByLabelText('Orden *')).toBeEnabled())
    expect(screen.getByLabelText('Orden *')).toHaveValue('')
    expect(fetchMock.mock.calls.some(([url]) => String(url).includes('resumen-facturacion'))).toBe(false)
    fireEvent.change(screen.getByLabelText('Orden *'), { target: { value: 'Ana' } })
    await waitFor(() => expect(fetchMock.mock.calls.some(([url]) => String(url).includes('search=Ana'))).toBe(true))
    fireEvent.click(await screen.findByRole('button', { name: 'Cargar más resultados' }))
    await screen.findByRole('option', { name: 'OS-2' })
    fireEvent.click(await screen.findByRole('option', { name: 'OS-2' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Revisar y generar' })).toBeEnabled())
    expect(screen.getByLabelText('Orden *')).toHaveValue('OS-2')
    expect(fetchMock.mock.calls.some(([url]) => String(url).includes('/ordenes?page=1&pageSize=30&search=Ana&estado=LISTO'))).toBe(true)
    expect(screen.getByRole('region', { name: 'Resumen de facturación' })).toHaveTextContent('103.77')
    expect(posts(fetchMock)).toHaveLength(0)
  })
  it('muestra importes oficiales sin sumar y reconsulta al cambiar tasa; bloquea tasa inválida', async () => {
    const fetchMock = mockBilling()
    render(<FacturacionPage />)
    await newInvoice()
    const summary = screen.getByRole('region', { name: 'Resumen de facturación' })
    expect(summary).toHaveTextContent('Q 103.77')
    expect(summary).toHaveTextContent('Q 0.77')
    fireEvent.change(screen.getByLabelText('Impuesto (%) *'), { target: { value: '0' } })
    await waitFor(() => expect(fetchMock.mock.calls.some(([url]) => String(url).endsWith('porcentajeImpuesto=0.00'))).toBe(true))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Revisar y generar' })).toBeEnabled())
    fireEvent.change(screen.getByLabelText('Impuesto (%) *'), { target: { value: '100.01' } })
    expect(screen.getByRole('button', { name: 'Revisar y generar' })).toBeDisabled()
    expect(screen.queryByRole('region', { name: 'Resumen de facturación' })).not.toBeInTheDocument()
    expect(fetchMock.mock.calls.some(([url]) => String(url).endsWith('porcentajeImpuesto=100.01'))).toBe(false)
  })
  it('exige confirmación, permite volver conservando datos y envía sólo datos fiscales/tasa', async () => {
    const fetchMock = mockBilling()
    const success = vi.spyOn(toast, 'success')
    render(<FacturacionPage />)
    let dialog = await reviewInvoice()
    expect(dialog).toHaveTextContent('Total: Q 103.77')
    expect(posts(fetchMock)).toHaveLength(0)
    fireEvent.click(within(dialog).getByRole('button', { name: 'Volver' }))
    expect(screen.getByLabelText('Nombre de facturación')).toHaveValue('  Ana Fiscal  ')
    fireEvent.click(screen.getByRole('button', { name: 'Revisar y generar' }))
    dialog = await screen.findByRole('dialog')
    fireEvent.click(within(dialog).getByRole('button', { name: 'Generar factura' }))
    await waitFor(() => expect(success).toHaveBeenCalledWith('Factura F-7 generada.'))
    expect(posts(fetchMock)).toHaveLength(1)
    expect(posts(fetchMock)[0][0]).toBe('/api/v1/ordenes/2/factura')
    expect(JSON.parse(String(posts(fetchMock)[0][1]?.body))).toEqual({ nitFacturacion: null, nombreFacturacion: 'Ana Fiscal', direccionFacturacion: null, porcentajeImpuesto: '12.00' })
    await waitFor(() => expect(fetchMock.mock.calls.some(([url]) => url === '/api/v1/facturas/7')).toBe(true))
    expect(screen.queryByRole('form', { name: 'Datos de facturación' })).not.toBeInTheDocument()
  })
  it('bloquea doble confirmación y el cierre mientras espera respuesta', async () => {
    let resolve!: (response: Response) => void
    const fetchMock = mockBilling((_url, init) => init?.method === 'POST' ? new Promise<Response>(done => { resolve = done }) : undefined)
    render(<FacturacionPage />)
    const dialog = await reviewInvoice()
    const confirm = within(dialog).getByRole('button', { name: 'Generar factura' })
    fireEvent.click(confirm); fireEvent.click(confirm)
    await waitFor(() => expect(posts(fetchMock)).toHaveLength(1))
    expect(within(dialog).getByRole('button', { name: 'Volver' })).toBeDisabled()
    fireEvent.click(within(dialog).getByRole('button', { name: 'Cerrar diálogo' }))
    expect(screen.getByRole('dialog')).toBeVisible()
    resolve(json({ data: invoiceResult }, 201))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  })
  it.each([400, 409])('conserva datos fiscales y muestra detalles HTTP %s dentro de la confirmación sin éxito', async status => {
    const fetchMock = mockBilling((_url, init) => init?.method === 'POST' ? failure(status, 'No se puede emitir.', { nombreFacturacion: ['Revisa el nombre fiscal.'] }) : undefined)
    const success = vi.spyOn(toast, 'success')
    render(<FacturacionPage />)
    const dialog = await reviewInvoice()
    fireEvent.click(within(dialog).getByRole('button', { name: 'Generar factura' }))
    expect(await within(dialog).findByRole('alert')).toHaveTextContent('nombreFacturacion: Revisa el nombre fiscal.')
    fireEvent.click(within(dialog).getByRole('button', { name: 'Volver' }))
    expect(screen.getByLabelText('Nombre de facturación')).toHaveValue('  Ana Fiscal  ')
    expect(posts(fetchMock)).toHaveLength(1); expect(success).not.toHaveBeenCalled()
  })
  it('no afirma emisión con red interrumpida y bloquea reenvío ambiguo', async () => {
    const fetchMock = mockBilling((_url, init) => init?.method === 'POST' ? Promise.reject(new TypeError('Network')) : undefined)
    const success = vi.spyOn(toast, 'success')
    render(<FacturacionPage />)
    const dialog = await reviewInvoice()
    fireEvent.click(within(dialog).getByRole('button', { name: 'Generar factura' }))
    expect(await within(dialog).findByRole('alert')).toHaveTextContent('El resultado no está confirmado')
    expect(within(dialog).getByRole('button', { name: 'Generar factura' })).toBeDisabled()
    expect(posts(fetchMock)).toHaveLength(1); expect(success).not.toHaveBeenCalled()
  })
  it.each(['facturada', 'no-listo', 'preview-error'])('bloquea emisión si la orden está %s', async condition => {
    const fetchMock = mockBilling(url => {
      if (url.pathname === '/api/v1/ordenes/2') return json({ data: { ...orden, estado: condition === 'no-listo' ? 'REPARACION' : 'LISTO', factura: condition === 'facturada' ? factura : null } })
      if (condition === 'preview-error' && url.pathname.includes('resumen-facturacion')) return failure(409, 'La orden cambió.')
      return undefined
    })
    render(<FacturacionPage />)
    fireEvent.click(screen.getByRole('button', { name: 'Nueva factura' }))
    await waitFor(() => expect(screen.getByLabelText('Orden *')).toBeEnabled())
    fireEvent.click(await screen.findByRole('option', { name: 'OS-2' }))
    await screen.findAllByRole('alert')
    expect(screen.getByRole('button', { name: 'Revisar y generar' })).toBeDisabled()
    if (condition === 'facturada') {
      fireEvent.click(screen.getByRole('button', { name: 'Ver factura existente' }))
      await screen.findByText('F-1 · EMITIDA')
    }
    expect(posts(fetchMock)).toHaveLength(0)
  })
  it('cancelar limpia el formulario, restaura foco y no usa almacenamiento', async () => {
    const storage = vi.spyOn(Storage.prototype, 'setItem')
    const fetchMock = mockBilling()
    render(<FacturacionPage />)
    await newInvoice()
    fireEvent.change(screen.getByLabelText('Nombre de facturación'), { target: { value: 'Ana Fiscal' } })
    fireEvent.click(screen.getByRole('button', { name: 'Cancelar' }))
    expect(screen.getByRole('button', { name: 'Nueva factura' })).toHaveFocus()
    fireEvent.click(screen.getByRole('button', { name: 'Nueva factura' }))
    expect(screen.getByLabelText('Nombre de facturación')).toHaveValue('')
    expect(storage).not.toHaveBeenCalled(); expect(posts(fetchMock)).toHaveLength(0)
  })
})

describe('anulación de pago con motivo y confirmación', () => {
  it('sólo ofrece pagos aplicados, confirma motivo y refresca saldo/historial después de éxito', async () => {
    let cancelled = false
    const fetchMock = mockBilling((url, init) => {
      if (init?.method === 'POST') { cancelled = true; return json({ data: { idPago: 1, estado: 'ANULADO', saldo: '11.20', estadoFactura: 'EMITIDA' } }) }
      if (cancelled && url.pathname === '/api/v1/facturas/1') return json({ data: { ...factura, saldo: '11.20', pagos: factura.pagos.map(pago => ({ ...pago, estado: 'ANULADO', motivoAnulacion: pago.idPago === 1 ? 'Referencia equivocada' : pago.motivoAnulacion })) } })
      return undefined
    })
    const success = vi.spyOn(toast, 'success')
    const { client } = render(<FacturacionPage />)
    const invalidate = vi.spyOn(client, 'invalidateQueries')
    const dialog = await reviewCancellation()
    expect(dialog).toHaveTextContent('Motivo: Referencia equivocada')
    expect(screen.queryByRole('button', { name: /Anular pago #2/ })).not.toBeInTheDocument()
    expect(posts(fetchMock)).toHaveLength(0)
    fireEvent.click(within(dialog).getByRole('button', { name: 'Anular pago' }))
    await waitFor(() => expect(success).toHaveBeenCalledWith('Pago anulado correctamente.'))
    expect(posts(fetchMock)).toHaveLength(1)
    expect(posts(fetchMock)[0][0]).toBe('/api/v1/pagos/1/anular')
    expect(JSON.parse(String(posts(fetchMock)[0][1]?.body))).toEqual({ motivo: 'Referencia equivocada' })
    await waitFor(() => expect(screen.getByRole('table', { name: 'Pagos de la factura' })).toHaveTextContent('Referencia equivocada'))
    expect(screen.getByText('Saldo (Q)').nextElementSibling).toHaveTextContent('11.20')
    for (const key of ['facturas', 'dashboard', 'ordenes']) expect(invalidate).toHaveBeenCalledWith({ queryKey: [key] })
  })
  it('volver no envía anulación y conserva motivo; exige motivo no vacío', async () => {
    const fetchMock = mockBilling()
    render(<FacturacionPage />)
    const dialog = await reviewCancellation()
    fireEvent.click(within(dialog).getByRole('button', { name: 'Volver' }))
    expect(screen.getByLabelText('Motivo de anulación *')).toHaveValue('  Referencia equivocada  ')
    fireEvent.change(screen.getByLabelText('Motivo de anulación *'), { target: { value: '  ' } })
    fireEvent.click(screen.getByRole('button', { name: 'Revisar anulación' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Este campo es obligatorio')
    expect(posts(fetchMock)).toHaveLength(0)
  })
  it.each([400, 409, 503])('conserva motivo tras HTTP %s y nunca notifica éxito', async status => {
    const fetchMock = mockBilling((_url, init) => init?.method === 'POST' ? failure(status, 'No se pudo anular.', { motivo: ['Revisa el motivo.'] }) : undefined)
    const success = vi.spyOn(toast, 'success')
    render(<FacturacionPage />)
    const dialog = await reviewCancellation()
    fireEvent.click(within(dialog).getByRole('button', { name: 'Anular pago' }))
    expect(await within(dialog).findByRole('alert')).toHaveTextContent('motivo: Revisa el motivo.')
    fireEvent.click(within(dialog).getByRole('button', { name: 'Volver' }))
    expect(screen.getByLabelText('Motivo de anulación *')).toHaveValue('  Referencia equivocada  ')
    expect(posts(fetchMock)).toHaveLength(1); expect(success).not.toHaveBeenCalled()
  })
  it('bloquea doble envío durante anulación', async () => {
    let resolve!: (response: Response) => void
    const fetchMock = mockBilling((_url, init) => init?.method === 'POST' ? new Promise<Response>(done => { resolve = done }) : undefined)
    render(<FacturacionPage />)
    const dialog = await reviewCancellation()
    const button = within(dialog).getByRole('button', { name: 'Anular pago' })
    fireEvent.click(button); fireEvent.click(button)
    await waitFor(() => expect(posts(fetchMock)).toHaveLength(1))
    expect(within(dialog).getByRole('button', { name: 'Volver' })).toBeDisabled()
    resolve(json({ data: { idPago: 1, estado: 'ANULADO', saldo: '11.20', estadoFactura: 'EMITIDA' } }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  })
  it('no permite anular después de entrega aunque la factura tenga pagos aplicados', async () => {
    const fetchMock = mockBilling(url => url.pathname === '/api/v1/ordenes/2' ? json({ data: { ...orden, estado: 'ENTREGADO', entrega: { idEntrega: 1 } } }) : undefined)
    render(<FacturacionPage />)
    fireEvent.click(await screen.findByRole('button', { name: 'Ver factura F-1' }))
    await screen.findByText('La orden ya fue entregada. No se permite anular sus pagos.')
    expect(screen.getByRole('button', { name: /Anular pago #1/ })).toBeDisabled()
    expect(posts(fetchMock)).toHaveLength(0)
  })
})
